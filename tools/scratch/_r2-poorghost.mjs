import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
const b = await chromium.launch({ args: ['--use-angle=metal','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--mute-audio','--hide-scrollbars'] });
const p = await b.newPage({ viewport: { width: 1920, height: 1080 } });
await p.route('**/@vite/client', (r) => r.fulfill({ status: 200, contentType: 'application/javascript', body: 'export const createHotContext = () => ({accept(){},dispose(){},prune(){},invalidate(){},on(){},off(){},send(){}}); export const injectQuery=(u)=>u; export const removeStyle=()=>{};' }));
await p.goto('http://localhost:5273/?q=ultra');
await p.waitForFunction(() => !!window.__game, null, { timeout: 90000 });
await p.evaluate(() => document.getElementById('boot')?.remove());
const state = process.argv[2] ?? 'poor';
const pt = await p.evaluate(async (st) => {
  const g = window.__game;
  g.state.elements = ['fire','water','nature','earth','light','dark'];
  g.state.pendingElementPicks = 0; g.hud.closeElementPicker(); g.state.phase = 'prep';
  g.state.gold = st === 'poor' ? 10 : 99999;
  g.hud.refreshBuildBar();
  g.setBuildSelection('fire');
  const c = 10, r = 8;
  const w = g.grid.towerCentreToWorld(c, r, {});
  const V = g.camera.position.constructor;
  const v = new V(w.x, 0, w.z).project(g.camera);
  const sx = Math.round((v.x * 0.5 + 0.5) * window.innerWidth);
  const sy = Math.round((-v.y * 0.5 + 0.5) * window.innerHeight);
  g.canvas.dispatchEvent(new PointerEvent('pointermove', { clientX: sx, clientY: sy, bubbles: true }));
  await new Promise((r2) => setTimeout(r2, 1200));
  return { sx, sy, reason: g.hover.reason };
}, state);
console.log(JSON.stringify(pt));
writeFileSync(process.argv[3] ?? 'shots/poorghost.png', await p.screenshot({ type: 'png', timeout: 120000 }));
await b.close();
